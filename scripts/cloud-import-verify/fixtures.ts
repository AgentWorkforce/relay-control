/** Deliberately small reference shapes. This is not the production importer.
 * Contract projections will be finalized against scripts/cloud-import/mapping.ts.
 */
export async function seedFixtures(client: Client): Promise<void> {
  await client.query(`DROP SCHEMA IF EXISTS cloud_fixture CASCADE;
    DROP SCHEMA IF EXISTS control_fixture CASCADE;
    CREATE SCHEMA cloud_fixture; CREATE SCHEMA control_fixture;
    CREATE TABLE cloud_fixture.users (uuid uuid PRIMARY KEY, email text NOT NULL UNIQUE, name text NOT NULL);
    CREATE TABLE cloud_fixture.organizations (uuid uuid PRIMARY KEY, name text NOT NULL);
    CREATE TABLE cloud_fixture.memberships (
      organization_uuid uuid REFERENCES cloud_fixture.organizations(uuid),
      user_uuid uuid REFERENCES cloud_fixture.users(uuid), role text NOT NULL,
      PRIMARY KEY(organization_uuid,user_uuid));
    CREATE TABLE cloud_fixture.workspaces (
      id text PRIMARY KEY, uuid uuid UNIQUE NOT NULL,
      organization_uuid uuid NOT NULL REFERENCES cloud_fixture.organizations(uuid),
      name text NOT NULL, settings jsonb, created_at timestamptz NOT NULL);
    CREATE TABLE control_fixture.users (id uuid PRIMARY KEY, email text NOT NULL UNIQUE, name text NOT NULL);
    CREATE TABLE control_fixture.organizations (id uuid PRIMARY KEY, name text NOT NULL);
    CREATE TABLE control_fixture.memberships (
      organization_id uuid REFERENCES control_fixture.organizations(id),
      user_id uuid REFERENCES control_fixture.users(id), role text NOT NULL,
      PRIMARY KEY(organization_id,user_id));
    CREATE TABLE control_fixture.workspaces (
      id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES control_fixture.organizations(id),
      cloud_relay_workspace_id text NOT NULL UNIQUE,
      name text NOT NULL, settings jsonb, created_at timestamptz NOT NULL,
      key_ciphertext text NOT NULL);
    CREATE TABLE control_fixture.provider_connections (
      workspace_id uuid PRIMARY KEY REFERENCES control_fixture.workspaces(id), credentials_ciphertext text NOT NULL);
    CREATE TABLE control_fixture.sequence_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
    INSERT INTO control_fixture.sequence_probe VALUES (9007199254740993);
    SELECT setval(pg_get_serial_sequence('control_fixture.sequence_probe','id'),9007199254740993,true)`);
  await client.query(`INSERT INTO cloud_fixture.organizations VALUES ($1,'Org A'),($2,'Org B')`,
    [fixtureIds.org, fixtureIds.otherOrg]);
  await client.query("INSERT INTO cloud_fixture.users VALUES($1,'fixture@example.invalid','Fixture Person')",[fixtureIds.user]);
  await client.query("INSERT INTO cloud_fixture.memberships VALUES($1,$3,'owner'),($2,$3,'member')",
    [fixtureIds.org,fixtureIds.otherOrg,fixtureIds.user]);
  await client.query(`INSERT INTO cloud_fixture.workspaces VALUES
    ('rw_actual-text-01',$1,$2,'Alpha','{"nested":{"b":2,"a":1},"n":9007199254740993}', '2026-11-09T04:00:00Z'),
    ('rw_not_a_uuid_02',$3,$4,'Beta',NULL,'2026-11-09T05:00:00Z')`,
  [fixtureIds.workspace, fixtureIds.org, fixtureIds.otherWorkspace, fixtureIds.otherOrg]);
  // Reference target only: makes the independent verifier testable before importer lands.
  await client.query("INSERT INTO control_fixture.users SELECT uuid,email,name FROM cloud_fixture.users");
  await client.query("INSERT INTO control_fixture.organizations SELECT uuid,name FROM cloud_fixture.organizations");
  await client.query("INSERT INTO control_fixture.memberships SELECT organization_uuid,user_uuid,role FROM cloud_fixture.memberships");
  await client.query(`INSERT INTO control_fixture.workspaces
    SELECT uuid,organization_uuid,id,name,settings,created_at,$1 FROM cloud_fixture.workspaces`,
  [encryptSecret("synthetic-relaycast-key", fixtureKeyring.active)]);
  await client.query("UPDATE control_fixture.workspaces SET key_ciphertext=$1 WHERE id=$2",
    [encryptSecret("synthetic-rotated-key", fixtureKeyring.previous!), fixtureIds.otherWorkspace]);
  await client.query("INSERT INTO control_fixture.provider_connections VALUES($1,$2)",
    [fixtureIds.workspace,encryptSecret('{"refreshToken":"synthetic-refresh"}',fixtureKeyring.active)]);
}

