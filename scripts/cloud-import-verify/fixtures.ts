/** Deliberately small reference shapes. This is not the production importer.
 * Contract projections will be finalized against scripts/cloud-import/mapping.ts.
 */
export async function seedFixtures(client: Client): Promise<void> {
  await client.query(`DROP SCHEMA IF EXISTS cloud_fixture CASCADE;
    DROP SCHEMA IF EXISTS control_fixture CASCADE;
    CREATE SCHEMA cloud_fixture; CREATE SCHEMA control_fixture;
    CREATE TABLE cloud_fixture.users (id uuid PRIMARY KEY, primary_email text, name text);
    CREATE TABLE cloud_fixture.organizations (id uuid PRIMARY KEY, name text NOT NULL);
    CREATE TABLE cloud_fixture.memberships (
      organization_id uuid REFERENCES cloud_fixture.organizations(id),
      user_id uuid REFERENCES cloud_fixture.users(id), role text NOT NULL, status text NOT NULL,
      PRIMARY KEY(organization_id,user_id));
    CREATE TABLE cloud_fixture.relay_workspaces (
      id text PRIMARY KEY, relaycast_workspace_id text NOT NULL, relaycast_api_key text NOT NULL);
    CREATE TABLE cloud_fixture.workspaces (
      id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES cloud_fixture.organizations(id),
      relay_workspace_id text REFERENCES cloud_fixture.relay_workspaces(id),
      name text NOT NULL, created_at timestamptz NOT NULL);
    CREATE TABLE cloud_fixture.payload_probe (id integer PRIMARY KEY, payload jsonb);
    CREATE TABLE control_fixture.payload_probe (id integer PRIMARY KEY, payload jsonb);
    CREATE TABLE control_fixture.users (id uuid PRIMARY KEY, email text NOT NULL UNIQUE, name text NOT NULL);
    CREATE TABLE control_fixture.organizations (id uuid PRIMARY KEY, name text NOT NULL);
    CREATE TABLE control_fixture.memberships (
      organization_id uuid REFERENCES control_fixture.organizations(id),
      user_id uuid REFERENCES control_fixture.users(id), role text NOT NULL,
      PRIMARY KEY(organization_id,user_id));
    CREATE TABLE control_fixture.workspaces (
      id uuid PRIMARY KEY, organization_id uuid NOT NULL REFERENCES control_fixture.organizations(id),
      cloud_relay_workspace_id text NOT NULL UNIQUE,
      relaycast_workspace_id text NOT NULL, name text NOT NULL, created_at timestamptz NOT NULL,
      relaycast_api_key_ciphertext text NOT NULL,
      UNIQUE(organization_id,relaycast_workspace_id));
    CREATE TABLE control_fixture.provider_connections (
      workspace_id uuid PRIMARY KEY REFERENCES control_fixture.workspaces(id), credentials_ciphertext text NOT NULL);
    CREATE TABLE cloud_fixture.publish_probe (publish_seq bigint);
    CREATE TABLE control_fixture.publish_probe (publish_seq bigint);
    INSERT INTO cloud_fixture.publish_probe VALUES(9007199254740993);
    INSERT INTO control_fixture.publish_probe SELECT * FROM cloud_fixture.publish_probe;
    CREATE SEQUENCE control_fixture.desktop_feed_publish_seq;
    SELECT setval('control_fixture.desktop_feed_publish_seq',9007199254740993,true);
    CREATE TABLE control_fixture.password_credentials (
      user_id uuid PRIMARY KEY REFERENCES control_fixture.users(id),password_hash text NOT NULL,pepper_version integer);
    CREATE TABLE control_fixture.sequence_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
    INSERT INTO control_fixture.sequence_probe VALUES (9007199254740993);
    SELECT setval(pg_get_serial_sequence('control_fixture.sequence_probe','id'),9007199254740993,true)`);
  await client.query(`INSERT INTO cloud_fixture.organizations VALUES ($1,'Org A'),($2,'Org B')`,
    [fixtureIds.org, fixtureIds.otherOrg]);
  await client.query("INSERT INTO cloud_fixture.users VALUES($1,'Fixture@example.invalid','Fixture Person'),($2,'Fallback@example.invalid',NULL)",
    [fixtureIds.user,fixtureIds.otherUser]);
  await client.query("INSERT INTO cloud_fixture.memberships VALUES($1,$3,'owner','active'),($2,$3,'member','active'),($1,$4,'member','inactive')",
    [fixtureIds.org,fixtureIds.otherOrg,fixtureIds.user,fixtureIds.otherUser]);
  await client.query("INSERT INTO cloud_fixture.relay_workspaces VALUES($1,$2,'synthetic-relaycast-key'),($3,$4,'synthetic-rotated-key')",
    [fixtureIds.relayWorkspace,fixtureIds.relaycastWorkspace,fixtureIds.otherRelayWorkspace,fixtureIds.otherRelaycastWorkspace]);
  await client.query(`INSERT INTO cloud_fixture.workspaces VALUES
    ($1,$2,$3,'Alpha','2026-11-09T04:00:00Z'),
    ($4,$5,$6,'Beta','2026-11-09T05:00:00Z')`,
  [fixtureIds.workspace,fixtureIds.org,fixtureIds.relayWorkspace,fixtureIds.otherWorkspace,fixtureIds.otherOrg,fixtureIds.otherRelayWorkspace]);
  // Engine stress payloads are deliberately separate from production-shaped identity rows.
  await client.query(`INSERT INTO cloud_fixture.payload_probe VALUES(1,'{"nested":{"b":2,"a":1},"n":9007199254740993}');
    INSERT INTO control_fixture.payload_probe SELECT * FROM cloud_fixture.payload_probe`);
  // Reference target only: makes the independent verifier testable before importer lands.
  await client.query("INSERT INTO control_fixture.users SELECT id,lower(primary_email),coalesce(name,lower(primary_email)) FROM cloud_fixture.users");
  await client.query("INSERT INTO control_fixture.password_credentials VALUES($1,'synthetic-hash-placeholder',NULL)",[fixtureIds.user]);
  await client.query("INSERT INTO control_fixture.organizations SELECT id,name FROM cloud_fixture.organizations");
  await client.query("INSERT INTO control_fixture.memberships SELECT organization_id,user_id,role FROM cloud_fixture.memberships WHERE status='active'");
  await client.query(`INSERT INTO control_fixture.workspaces
    SELECT w.id,w.organization_id,w.relay_workspace_id,r.relaycast_workspace_id,w.name,w.created_at,$1
    FROM cloud_fixture.workspaces w JOIN cloud_fixture.relay_workspaces r ON r.id=w.relay_workspace_id`,
  [encryptSecret("synthetic-relaycast-key", fixtureKeyring.active)]);
  await client.query("UPDATE control_fixture.workspaces SET relaycast_api_key_ciphertext=$1 WHERE id=$2",
    [encryptSecret("synthetic-rotated-key", fixtureKeyring.previous!), fixtureIds.otherWorkspace]);
  await client.query("INSERT INTO control_fixture.provider_connections VALUES($1,$2)",
    [fixtureIds.workspace,encryptSecret('{"refreshToken":"synthetic-refresh"}',fixtureKeyring.active)]);
}

